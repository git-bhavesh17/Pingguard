        "for _ in range(3):\n"
        "    for true_lbl, sc in zip(y_val, champ_val_scores):\n"
        "        st = get_rl_state(float(sc))\n"
        "        for act in RL_ACTIONS:\n"
        "            r = reward_map[(int(true_lbl), act)]\n"
        "            q_table[st][act] = round(q_table[st][act] + alpha * (r + gamma * max(q_table[st].values()) - q_table[st][act]), 3)\n\n"
        "q_df = pd.DataFrame(q_table).T\n"
